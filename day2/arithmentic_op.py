# operators: symbols that are used to perform certain task

# arithmetic: mathematic operations
a = 10
b = 5

# addition: +
print(a + b)

# subtraction: -
print(a - b)

# multiplication: *
print(a * b)

# division: /   float output
print(a / b)

# floor division: //    interger output
print(a // b)

# modulus: %    reminder
print(a % b)

# exponential: **   a to the power of b
print(a**b)