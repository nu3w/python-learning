# assignment operators: a value assigned to a variable

# equals to: =
a = 10

# add and assign: +=
a += 5      # a = a + 5    
print(a) 

# subtract and assign: -=
a -= 5      # a = a - 5
print(a)

# multiply and assign: *=
a *= 5      # a = a * 5
print(a)

# divide and assign: *=
a /= 5      # a = a / 5
print(a)

# floor divide and assign: *=
a //= 5      # a = a // 5
print(a)

# modulus and assign: *=
a %= 5      # a = a % 5
print(a)

# exponential and assign: *=
a **= 5      # a = a ** 5
print(a)