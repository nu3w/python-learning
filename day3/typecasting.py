# type casting: type conversion: change a datatype to another

# convert to string - str()
a = 15.45
print(type(a)) 
b = str(a)
print(type(b))

# convert to integer - int()
c = int(a)
print(type(c))

# convert to float - float()
d = float(c)
print(type(d))
print(d)

a = "hello"

# convert to list - list()
print(list(a))

# convert to tuple - tuple()
print(tuple(a))

# convert to set - set()
print(set(a))

# convert to dictionary - dict()
a = [(1, 'ram'), (2, 'sita')]
print(dict(a))