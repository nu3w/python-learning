# logical operator:

a = 10
b = 15
c = 5

# AND: True, if both conditions are true, else, False
print(a < b and b < c)      #False

# OR: True, if any one condition is true, else, False
print(a < b or b < c)       #True

# NOT: True, if the input is false and vice-versa
print(not a < b)        #False