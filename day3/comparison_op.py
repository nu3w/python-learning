# comparison operators: symbols used to compare values and return a boolean result (True or False)

a = 10
b = 15

# equals to: ==     True, if both values are same or equal, otherwise, False
print(a == b)     # False

# not equal: !=     True, if values are different, else, False
print(a != b)       # True

# greater than: >       True, if first value is greater than second, else, False
print(a > b)        # False

# less than: <      True, if first value is less than second, else, False
print(a < b)        #True

# greater or equal: >=     True, if first value is greater or equal to second, else, False
print(a >= b)       #False

# less or equal: <=     True, if first value is less or equal to second, else, False
print(a <= b)       #True
